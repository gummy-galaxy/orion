const AREA_BY_WORD = new Map(AREA_WORDS.flatMap(([area, words]) => words.map((word) => [word, area] as const)))
const AREA_ORDER = AREA_WORDS.map(([area]) => area)

function addWords(text: string | undefined, weight: number, scores: Map<CardArea, number>) {
  for (const word of text?.toLowerCase().match(/[a-z]+/g) ?? []) {
    const area = [word, word.replace(/s$/, ''), word.replace(/es$/, ''), word.replace(/(ed|ing)$/, '')]
      .map((form) => AREA_BY_WORD.get(form))
      .find(Boolean)

    if (area) scores.set(area, (scores.get(area) ?? 0) + weight)
  }
}

/** Reads which part of a system a card touches from the words in its title, then its note. */
export function getCardArea(title: string, note?: string): CardArea | undefined {
  const scores = new Map<CardArea, number>()

  addWords(title, 2, scores)
  addWords(note, 1, scores)

  let best: CardArea | undefined

  for (const area of AREA_ORDER) {
    if ((scores.get(area) ?? 0) > (best ? scores.get(best)! : 0)) best = area
  }

  return best
}
